// generateClient returns the content of client.go containing the Client struct
// and one set of CRUD methods per schema.
func (g *ClientGenerator) generateClient(defs []*schema.SchemaDefinition) (string, error) {
	var b strings.Builder

	b.WriteString("// Code generated by stellar-drive; DO NOT EDIT.\n")
	b.WriteString("package sdkclient\n\n")

	b.WriteString(`import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strconv"
)

`)

	baseURL := g.baseURL
	if baseURL == "" {
		baseURL = "http://localhost:8080"
	}

	// Client struct.
	fmt.Fprintf(&b, `// Client is a typed HTTP client for the stellar-drive API.
// All methods are safe for concurrent use.
type Client struct {
	baseURL    string
	httpClient *http.Client
}

// NewClient creates a Client with the given base URL. When httpClient is nil,
// http.DefaultClient is used.
func NewClient(baseURL string, httpClient *http.Client) *Client {
	if baseURL == "" {
		baseURL = %q
	}
	if httpClient == nil {
		httpClient = http.DefaultClient
	}
	return &Client{baseURL: baseURL, httpClient: httpClient}
}

`, baseURL)

	// Shared private helpers.
	b.WriteString(clientHelpers())

	// Per-schema methods.
	for _, def := range defs {
		writeClientMethods(&b, def)
	}

	return b.String(), nil
}

// clientHelpers returns the private helper methods that are shared across all
// schema-specific CRUD methods.
func clientHelpers() string {
	return `// do executes req, checks for a non-2xx status, and decodes the JSON body
// into out. out may be nil if the caller does not expect a body.
func (c *Client) do(ctx context.Context, req *http.Request, out any) error {
	req = req.WithContext(ctx)
	resp, err := c.httpClient.Do(req)
	if err != nil {
		return fmt.Errorf("http: %w", err)
	}
	defer resp.Body.Close()

	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return fmt.Errorf("read body: %w", err)
	}

	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		var apiErr APIError
		if jsonErr := json.Unmarshal(body, &apiErr); jsonErr != nil {
			return &APIError{StatusCode: resp.StatusCode, Message: string(body)}
		}
		apiErr.StatusCode = resp.StatusCode
		return &apiErr
	}

	if out != nil && len(body) > 0 {
		if err := json.Unmarshal(body, out); err != nil {
			return fmt.Errorf("decode response: %w", err)
		}
	}
	return nil
}

// newJSONRequest builds an HTTP request with a JSON-encoded body.
func (c *Client) newJSONRequest(method, path string, body any) (*http.Request, error) {
	var buf bytes.Buffer
	if err := json.NewEncoder(&buf).Encode(body); err != nil {
		return nil, fmt.Errorf("encode body: %w", err)
	}
	req, err := http.NewRequest(method, c.baseURL+path, &buf)
	if err != nil {
		return nil, fmt.Errorf("build request: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Accept", "application/json")
	return req, nil
}

// newRequest builds a plain HTTP request with no body.
func (c *Client) newRequest(method, path string) (*http.Request, error) {
	req, err := http.NewRequest(method, c.baseURL+path, nil)
	if err != nil {
		return nil, fmt.Errorf("build request: %w", err)
	}
	req.Header.Set("Accept", "application/json")
	return req, nil
}

`
}

// writeClientMethods appends the five CRUD methods for def to b.
func writeClientMethods(b *strings.Builder, def *schema.SchemaDefinition) {
	typeName := stringutil.ToPascalCase(def.Name)
	// Pluralise from the original schema name, not the PascalCase type name,
	// so "pet" → "pets" and the method is ListPets, not ListPetss.
	pluralTypeName := stringutil.ToPascalCase(stringutil.Pluralize(def.Name))
	// URL path uses the plural lower-case name, consistent with the REST adapter.
	basePath := "/" + strings.ToLower(stringutil.Pluralize(def.Name))

	// Create
	fmt.Fprintf(b, "// Create%s sends a POST request to create a new %s record.\n", typeName, def.Name)
	fmt.Fprintf(b, "func (c *Client) Create%s(ctx context.Context, input %sCreate) (*Document[%s], error) {\n", typeName, typeName, typeName)
	fmt.Fprintf(b, "\treq, err := c.newJSONRequest(http.MethodPost, %q, input)\n", basePath)
	fmt.Fprintf(b, "\tif err != nil {\n\t\treturn nil, fmt.Errorf(\"create %s: %%w\", err)\n\t}\n", def.Name)
	fmt.Fprintf(b, "\tvar env ResponseEnvelope[Document[%s]]\n", typeName)
	fmt.Fprintf(b, "\tif err := c.do(ctx, req, &env); err != nil {\n\t\treturn nil, fmt.Errorf(\"create %s: %%w\", err)\n\t}\n", def.Name)
	b.WriteString("\treturn &env.Data, nil\n}\n\n")

	// Get
	fmt.Fprintf(b, "// Get%s retrieves a single %s record by its entity ID.\n", typeName, def.Name)
	fmt.Fprintf(b, "func (c *Client) Get%s(ctx context.Context, id string) (*Document[%s], error) {\n", typeName, typeName)
	fmt.Fprintf(b, "\treq, err := c.newRequest(http.MethodGet, %q+\"/\"+id)\n", basePath)
	fmt.Fprintf(b, "\tif err != nil {\n\t\treturn nil, fmt.Errorf(\"get %s: %%w\", err)\n\t}\n", def.Name)
	fmt.Fprintf(b, "\tvar env ResponseEnvelope[Document[%s]]\n", typeName)
	fmt.Fprintf(b, "\tif err := c.do(ctx, req, &env); err != nil {\n\t\treturn nil, fmt.Errorf(\"get %s: %%w\", err)\n\t}\n", def.Name)
	b.WriteString("\treturn &env.Data, nil\n}\n\n")

	// List — method name uses the proper plural of the type name.
	fmt.Fprintf(b, "// List%s retrieves a paginated list of %s records.\n", pluralTypeName, def.Name)
	fmt.Fprintf(b, "func (c *Client) List%s(ctx context.Context, opts ListOptions) (*ListResult[Document[%s]], error) {\n", pluralTypeName, typeName)
	b.WriteString("\tq := url.Values{}\n")
	b.WriteString("\tif opts.Limit > 0 {\n\t\tq.Set(\"limit\", strconv.Itoa(opts.Limit))\n\t}\n")
	b.WriteString("\tif opts.Offset > 0 {\n\t\tq.Set(\"offset\", strconv.Itoa(opts.Offset))\n\t}\n")
	b.WriteString("\tif opts.Cursor != \"\" {\n\t\tq.Set(\"cursor\", opts.Cursor)\n\t}\n")
	fmt.Fprintf(b, "\tpath := %q\n", basePath)
	b.WriteString("\tif len(q) > 0 {\n\t\tpath += \"?\" + q.Encode()\n\t}\n")
	fmt.Fprintf(b, "\treq, err := c.newRequest(http.MethodGet, path)\n")
	fmt.Fprintf(b, "\tif err != nil {\n\t\treturn nil, fmt.Errorf(\"list %s: %%w\", err)\n\t}\n", def.Name)
	fmt.Fprintf(b, "\tvar env ResponseEnvelope[ListResult[Document[%s]]]\n", typeName)
	fmt.Fprintf(b, "\tif err := c.do(ctx, req, &env); err != nil {\n\t\treturn nil, fmt.Errorf(\"list %s: %%w\", err)\n\t}\n", def.Name)
	b.WriteString("\treturn &env.Data, nil\n}\n\n")

	// Update
	fmt.Fprintf(b, "// Update%s sends a PATCH request to partially update an existing %s record.\n", typeName, def.Name)
	fmt.Fprintf(b, "func (c *Client) Update%s(ctx context.Context, id string, input %sUpdate) (*Document[%s], error) {\n", typeName, typeName, typeName)
	fmt.Fprintf(b, "\treq, err := c.newJSONRequest(http.MethodPatch, %q+\"/\"+id, input)\n", basePath)
	fmt.Fprintf(b, "\tif err != nil {\n\t\treturn nil, fmt.Errorf(\"update %s: %%w\", err)\n\t}\n", def.Name)
	fmt.Fprintf(b, "\tvar env ResponseEnvelope[Document[%s]]\n", typeName)
	fmt.Fprintf(b, "\tif err := c.do(ctx, req, &env); err != nil {\n\t\treturn nil, fmt.Errorf(\"update %s: %%w\", err)\n\t}\n", def.Name)
	b.WriteString("\treturn &env.Data, nil\n}\n\n")

	// Delete
	fmt.Fprintf(b, "// Delete%s sends a DELETE request to remove a %s record by its entity ID.\n", typeName, def.Name)
	fmt.Fprintf(b, "func (c *Client) Delete%s(ctx context.Context, id string) error {\n", typeName)
	fmt.Fprintf(b, "\treq, err := c.newRequest(http.MethodDelete, %q+\"/\"+id)\n", basePath)
	fmt.Fprintf(b, "\tif err != nil {\n\t\treturn fmt.Errorf(\"delete %s: %%w\", err)\n\t}\n", def.Name)
	fmt.Fprintf(b, "\tif err := c.do(ctx, req, nil); err != nil {\n\t\treturn fmt.Errorf(\"delete %s: %%w\", err)\n\t}\n", def.Name)
	b.WriteString("\treturn nil\n}\n\n")
}

