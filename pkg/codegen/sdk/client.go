// ClientGenerator generates a typed Go HTTP client SDK from registered schemas.
// The generator produces string content for three files: models.go, client.go,
// and errors.go. It does not write to disk; callers receive the file map and
// decide what to do with it.
type ClientGenerator struct {
	registry   *schema.Registry
	baseURL    string
	modulePath string
	outputDir  string
}

// ClientOption configures a ClientGenerator.
type ClientOption func(*ClientGenerator)

// WithBaseURL sets the default base URL embedded in the generated client.
func WithBaseURL(url string) ClientOption {
	return func(g *ClientGenerator) {
		g.baseURL = url
	}
}

// WithModulePath sets the Go module path used in generated package declarations
// and import paths.
func WithModulePath(path string) ClientOption {
	return func(g *ClientGenerator) {
		g.modulePath = path
	}
}

// NewClientGenerator creates a new ClientGenerator that writes generated files
// into outputDir. The registry supplies schema definitions; opts apply optional
// configuration.
func NewClientGenerator(reg *schema.Registry, outputDir string, opts ...ClientOption) *ClientGenerator {
	g := &ClientGenerator{
		registry:  reg,
		outputDir: outputDir,
	}
	for _, o := range opts {
		o(g)
	}
	return g
}

// Generate produces the SDK source files as a map[filename]content. The three
// keys are "models.go", "client.go", and "errors.go". The generated code only
// depends on the Go standard library.
func (g *ClientGenerator) Generate() (map[string]string, error) {
	defs := g.registry.List()

	modelsContent, err := g.generateModels(defs)
	if err != nil {
		return nil, fmt.Errorf("sdk: generate models: %w", err)
	}

	clientContent, err := g.generateClient(defs)
	if err != nil {
		return nil, fmt.Errorf("sdk: generate client: %w", err)
	}

	errorsContent := g.generateErrors()

	return map[string]string{
		"models.go": modelsContent,
		"client.go": clientContent,
		"errors.go": errorsContent,
	}, nil
}

