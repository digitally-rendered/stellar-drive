// generateErrors returns the content of errors.go containing the APIError type.
func (g *ClientGenerator) generateErrors() string {
	return `// Code generated by stellar-drive; DO NOT EDIT.
package sdkclient

import (
	"encoding/json"
	"fmt"
)

// ErrorDetail provides additional context for a specific validation or
// application-level error.
type ErrorDetail struct {
	Field   string ` + "`json:\"field,omitempty\"`" + `
	Message string ` + "`json:\"message\"`" + `
	Code    string ` + "`json:\"code,omitempty\"`" + `
}

// ErrorResponse is the JSON body returned by the server on non-2xx responses.
type ErrorResponse struct {
	Code    string        ` + "`json:\"code,omitempty\"`" + `
	Message string        ` + "`json:\"message\"`" + `
	Details []ErrorDetail ` + "`json:\"details,omitempty\"`" + `
}

// APIError is returned by Client methods when the server responds with a
// non-2xx HTTP status code. It implements the error interface.
type APIError struct {
	StatusCode int
	Code       string
	Message    string
	Details    []ErrorDetail
}

// Error implements the error interface.
func (e *APIError) Error() string {
	if e.Code != "" {
		return fmt.Sprintf("api error %d (%s): %s", e.StatusCode, e.Code, e.Message)
	}
	return fmt.Sprintf("api error %d: %s", e.StatusCode, e.Message)
}

// UnmarshalJSON populates APIError from the ErrorResponse JSON shape.
func (e *APIError) UnmarshalJSON(data []byte) error {
	// Use a local alias to avoid infinite recursion.
	type alias ErrorResponse
	var r alias
	if err := json.Unmarshal(data, &r); err != nil {
		return err
	}
	e.Code = r.Code
	e.Message = r.Message
	e.Details = r.Details
	return nil
}
`
}
