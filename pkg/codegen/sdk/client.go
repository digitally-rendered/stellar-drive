// generateModels returns the content of models.go containing per-schema
// structs: {Name}, {Name}Create, {Name}Update, plus the generic Document
// wrapper and list helpers.
func (g *ClientGenerator) generateModels(defs []*schema.SchemaDefinition) (string, error) {
	var b strings.Builder

	b.WriteString("// Code generated by stellar-drive; DO NOT EDIT.\n")
	b.WriteString("package sdkclient\n\n")
	b.WriteString("import \"time\"\n\n")

	// Generic helpers that are schema-agnostic.
	b.WriteString(`// ResponseEnvelope wraps every API response with success/error metadata.
type ResponseEnvelope[T any] struct {
	Success bool           ` + "`json:\"success\"`" + `
	Data    T              ` + "`json:\"data,omitempty\"`" + `
	Error   *ErrorResponse ` + "`json:\"error,omitempty\"`" + `
}

// ListResult holds a page of items along with pagination state.
type ListResult[T any] struct {
	Items   []T    ` + "`json:\"items\"`" + `
	Total   int64  ` + "`json:\"total\"`" + `
	HasMore bool   ` + "`json:\"has_more\"`" + `
	Cursor  string ` + "`json:\"cursor,omitempty\"`" + `
}

// ListOptions parameterises a List request.
type ListOptions struct {
	Limit  int    ` + "`json:\"limit,omitempty\"`" + `
	Offset int    ` + "`json:\"offset,omitempty\"`" + `
	Cursor string ` + "`json:\"cursor,omitempty\"`" + `
}

// Document wraps any entity with its full set of server-generated audit fields.
type Document[T any] struct {
	ID            string     ` + "`json:\"id\"`" + `
	EntityID      string     ` + "`json:\"entity_id\"`" + `
	RecordVersion int64      ` + "`json:\"record_version\"`" + `
	SchemaVersion string     ` + "`json:\"schema_version\"`" + `
	SchemaName    string     ` + "`json:\"schema_name\"`" + `
	ETag          string     ` + "`json:\"etag\"`" + `
	CreatedAt     time.Time  ` + "`json:\"created_at\"`" + `
	UpdatedAt     time.Time  ` + "`json:\"updated_at\"`" + `
	DeletedAt     *time.Time ` + "`json:\"deleted_at,omitempty\"`" + `
	CreatedBy     string     ` + "`json:\"created_by,omitempty\"`" + `
	UpdatedBy     string     ` + "`json:\"updated_by,omitempty\"`" + `
	DeletedBy     string     ` + "`json:\"deleted_by,omitempty\"`" + `
	Data          T          ` + "`json:\"data\"`" + `
}

`)

	for _, def := range defs {
		if err := writeSchemaModels(&b, def); err != nil {
			return "", fmt.Errorf("schema %q: %w", def.Name, err)
		}
	}

	return b.String(), nil
}

// writeSchemaModels appends the three model variants for def to b.
func writeSchemaModels(b *strings.Builder, def *schema.SchemaDefinition) error {
	typeName := stringutil.ToPascalCase(def.Name)

	// Plain struct — fields only, no audit.
	fmt.Fprintf(b, "// %s represents the user-defined fields of a %s record.\n", typeName, def.Name)
	fmt.Fprintf(b, "type %s struct {\n", typeName)
	for _, f := range def.Fields {
		writeField(b, f, false)
	}
	b.WriteString("}\n\n")

	// Create variant — same fields, required have no omitempty.
	fmt.Fprintf(b, "// %sCreate carries the user-supplied fields for creating a new %s.\n", typeName, def.Name)
	fmt.Fprintf(b, "type %sCreate struct {\n", typeName)
	for _, f := range def.Fields {
		writeField(b, f, false)
	}
	b.WriteString("}\n\n")

	// Update variant — all fields are pointers (PATCH semantics).
	fmt.Fprintf(b, "// %sUpdate carries the fields the caller wishes to change (PATCH semantics).\n", typeName)
	fmt.Fprintf(b, "type %sUpdate struct {\n", typeName)
	for _, f := range def.Fields {
		writeField(b, f, true)
	}
	b.WriteString("}\n\n")

	return nil
}

// writeField appends a single struct field line to b.
// When forUpdate is true, scalar types are wrapped in a pointer.
func writeField(b *strings.Builder, f schema.FieldDefinition, forUpdate bool) {
	goName := stringutil.ToPascalCase(f.Name)
	goType := resolvedType(f)

	if forUpdate {
		goType = ptrType(goType)
	}

	tag := jsonFieldTag(f.Name, f.Required, forUpdate)
	fmt.Fprintf(b, "\t%s %s %s\n", goName, goType, tag)
}

// resolvedType returns the Go type for a field, falling back to "any" when no
// information is available.
func resolvedType(f schema.FieldDefinition) string {
	if f.GoType != "" {
		return f.GoType
	}
	switch f.JSONType {
	case "string":
		if f.Format == "date-time" {
			return "time.Time"
		}
		return "string"
	case "number":
		return "float64"
	case "integer":
		return "int64"
	case "boolean":
		return "bool"
	case "array":
		return "[]any"
	case "object":
		return "map[string]any"
	default:
		return "any"
	}
}

// ptrType wraps base in a pointer unless it is already a pointer, slice, map,
// or interface type.
func ptrType(base string) string {
	if strings.HasPrefix(base, "*") ||
		strings.HasPrefix(base, "[]") ||
		strings.HasPrefix(base, "map[") ||
		base == "any" {
		return base
	}
	return "*" + base
}

// jsonFieldTag builds a struct tag string.
func jsonFieldTag(name string, required, forUpdate bool) string {
	if required && !forUpdate {
		return fmt.Sprintf("`json:%q`", name)
	}
	return fmt.Sprintf("`json:\"%s,omitempty\"`", name)
}

